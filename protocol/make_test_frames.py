#!/usr/bin/env python3
"""Writes protocol/test_frames.txt: example frames that the firmware's tests (test/test_applink)
and the app's tests (app/crates/namforge-link) must both encode and decode identically.

This script is a third, independent implementation of the frame format in PROTOCOL.md
(it uses zlib's CRC-32), so the two real implementations are not just checked against
each other.

  python3 protocol/make_test_frames.py

File format, one frame per line, fields separated by " | ":
  name | type (hex) | flags (hex) | sequence (decimal) | payload (hex, "-" if empty) | whole frame (hex)
"""
import os
import struct
import zlib

MAGIC = bytes([0xF1, 0xD5])


def frame(ftype, flags, seq, payload):
    body = struct.pack("<BBHI", ftype, flags, seq, len(payload)) + payload
    return MAGIC + body + struct.pack("<I", zlib.crc32(body) & 0xFFFFFFFF)


def string(s):
    b = s.encode("utf-8")
    return struct.pack("<H", len(b)) + b


def pattern(n):
    # A deterministic byte pattern that covers all values, including the magic bytes.
    x, out = 12345, bytearray()
    for _ in range(n):
        x = (x * 1664525 + 1013904223) & 0xFFFFFFFF
        out.append(x >> 24)
    return bytes(out)


CASES = [
    ("empty request", 0x03, 0x00, 1, b""),
    ("hello request", 0x01, 0x00, 2, struct.pack("<H", 1) + string("NAM Forge 0.1.0")),
    ("hello reply", 0x01, 0x01, 2,
     struct.pack("<H", 1) + string("0.1.0") + struct.pack("<HIHHHHHI", 32, 48000, 64, 128, 95, 64, 67, 0xDEADBEEF)),
    ("set param", 0x10, 0x00, 3, struct.pack("<Hi", 2, 380)),
    ("set param reply", 0x10, 0x01, 3, struct.pack("<Hi", 2, 380)),
    ("param changed event", 0x11, 0x04, 0, struct.pack("<Hi", 39, 1)),
    ("error reply", 0x21, 0x03, 4, struct.pack("<H", 3) + string("No such preset")),
    ("one byte", 0x60, 0x04, 0, b"\x00"),
    ("highest sequence", 0x03, 0x00, 65535, b""),
    ("payload holding the magic bytes", 0x41, 0x00, 7, bytes([0xF1, 0xD5, 0xF1, 0xD5, 0x0A, 0x0D, 0xF1])),
    ("utf-8 string", 0x60, 0x04, 0, string("Écho – 7 弦")),
    ("300 pattern bytes", 0x41, 0x00, 8, pattern(300)),
    ("4096 pattern bytes", 0x41, 0x00, 9, pattern(4096)),
]


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    lines = ["# Generated by protocol/make_test_frames.py - do not edit.",
             "# name | type | flags | sequence | payload | frame"]
    for name, ftype, flags, seq, payload in CASES:
        lines.append(" | ".join([name, "%02x" % ftype, "%02x" % flags, str(seq),
                                 payload.hex() if payload else "-", frame(ftype, flags, seq, payload).hex()]))
    with open(os.path.join(here, "test_frames.txt"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote protocol/test_frames.txt (%d frames)" % len(CASES))


if __name__ == "__main__":
    main()
