# PlatformIO pre-script for environments that build the NAM reference engine
# (NeuralAmpModelerCore, MIT) for the Teensy.
#
# - Fetches pinned commits of NeuralAmpModelerCore and Eigen into third_party/ (git-ignored).
# - Adds the include paths and the few core sources the A2 fast path needs to the build.
# - Generates third_party/generated/a2_lite_model.h from the core's example A2 model:
#   the A2-Lite (3-channel) sub-model's config (JSON text) and weights (float array).
import json
import subprocess
from os import makedirs
from os.path import isdir, isfile, join

Import("env")

PROJECT = env.subst("$PROJECT_DIR")
TP = join(PROJECT, "third_party")

PINS = {
    "NeuralAmpModelerCore": ("https://github.com/sdatkinson/NeuralAmpModelerCore.git",
                             "d3189ed"),   # 2026-11-10, has NAM/wavenet/a2_fast.cpp
    "eigen": ("https://gitlab.com/libeigen/eigen.git",
              "bc3b39870ecb690a623a3f49149a358b95c5781d"),   # the commit the core pins as a submodule
}


def fetch(name):
    url, rev = PINS[name]
    dest = join(TP, name)
    if isdir(join(dest, ".git")):
        return dest
    print("nam_core.py: fetching %s @ %s" % (name, rev))
    makedirs(dest, exist_ok=True)
    def git(*args):
        subprocess.check_call(["git", "-C", dest] + list(args))
    git("init", "-q")
    git("remote", "add", "origin", url)
    try:
        git("fetch", "-q", "--depth", "1", "origin", rev)
    except subprocess.CalledProcessError:
        git("fetch", "-q", "origin")          # server refused a short hash / shallow fetch
        git("checkout", "-q", rev)
    else:
        git("checkout", "-q", "FETCH_HEAD")
    return dest


def generate_model_header(core):
    out_dir = join(TP, "generated")
    out = join(out_dir, "a2_lite_model.h")
    if isfile(out):
        return out_dir
    with open(join(core, "example_models", "A2.nam")) as f:
        container = json.load(f)
    lite = None
    for sub in container["config"]["submodels"]:
        model = sub["model"]
        if model["architecture"] == "WaveNet" and model["config"]["layers"][0]["channels"] == 3:
            lite = model
    if lite is None:
        raise RuntimeError("A2.nam has no 3-channel (A2-Lite) sub-model")
    config = json.dumps(lite["config"], separators=(",", ":"))
    weights = lite["weights"]
    makedirs(out_dir, exist_ok=True)
    with open(out, "w") as f:
        f.write("// Generated by scripts/nam_core.py from NeuralAmpModelerCore/example_models/A2.nam.\n")
        f.write("// A2-Lite (3-channel) sub-model: config as JSON text, weights as float32.\n")
        f.write("#pragma once\n#include <stddef.h>\n\n")
        f.write("static const double kA2LiteSampleRate = %r;\n" % float(container["sample_rate"]))
        f.write("static const char kA2LiteConfigJson[] = R\"NAMJSON(%s)NAMJSON\";\n\n" % config)
        f.write("static const size_t kA2LiteWeightCount = %d;\n" % len(weights))
        f.write("static const float kA2LiteWeights[%d] = {\n" % len(weights))
        for i in range(0, len(weights), 6):
            f.write("    " + ", ".join("%.9gf" % w if ("." in "%.9g" % w or "e" in "%.9g" % w or "n" in "%.9g" % w)
                                       else "%.9g.0f" % w for w in weights[i:i + 6]) + ",\n")
        f.write("};\n")
    return out_dir


core = fetch("NeuralAmpModelerCore")
eigen = fetch("eigen")
generated = generate_model_header(core)

for d in [core, join(core, "Dependencies", "nlohmann"), eigen, generated]:
    env.Append(CCFLAGS=["-isystem", d])

env.Append(CPPDEFINES=["NAM_SAMPLE_FLOAT", "NAM_ENABLE_A2_FAST"])

# Only what the A2 fast path needs. Everything else in the core (LSTM, ConvNet, the generic
# WaveNet, file loading) stays out of the firmware.
#
# Per-file flags (the Teensy core itself keeps its normal flags):
# - C++ exceptions on, because the core library throws on bad models. They cannot be enabled
#   globally: unwind tables for the core's FLASHMEM functions do not link (flash is too far
#   from RAM for the table's 31-bit offsets).
# - dsp.cpp has one thread_local variable (a default flag). Bare-metal Teensy has a single
#   thread and no thread-local storage runtime, so it becomes an ordinary global.
def nam_flags(env, node):
    cxxflags = [f for f in env["CXXFLAGS"] if f != "-fno-exceptions"] + ["-fexceptions"]
    defines = list(env["CPPDEFINES"])
    if str(node).endswith("dsp.cpp"):
        defines.append(("thread_local", ""))
    return env.Object(node, CXXFLAGS=cxxflags, CPPDEFINES=defines)


env.AddBuildMiddleware(nam_flags, "*/NAM/*.cpp")          # also matches NAM/wavenet/*.cpp
env.AddBuildMiddleware(nam_flags, "*/hw_tests/nam_bench.cpp")
env.BuildSources(
    join("$BUILD_DIR", "nam_core"),
    join(core, "NAM"),
    src_filter=["-<*>", "+<dsp.cpp>", "+<activations.cpp>", "+<wavenet/a2_fast.cpp>"],
)
